#!/usr/bin/env python3
"""P3: lift the Thumb functions no src/ TU defines into C (static recompilation), so the port runs them instead of
trap stand-ins.

Every lifted function has the uniform host prototype
    u32 f(u32 r0, u32 r1, u32 r2, u32 r3, u32 s0..s5)    (s0..s5 = the first stack arguments)
and returns r0 (r1 goes to the global ffc_r1). Registers are C locals, the stack frame is a local array, flags are
computed per instruction (clang drops the dead ones). Memory is accessed through raw 32-bit pointers: registers hold
host addresses because every literal-pool word with a relocation becomes the host address of its target symbol
(relocs.txt), and the DS address space itself is mapped by port/src/hal.c. PC-relative values point into a
static copy of the function's bytes, so switch tables read and `add pc, rX` dispatches back to a label.

ARM-mode functions and undecodable code are left as stand-ins (port_gendata.py traps).

usage: port_lift.py --objs build/port/host/objs.txt --out build/port/host/lift [--chunks 32]
"""
import argparse
import bisect
import os
import re
import subprocess
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ffclib  # noqa: E402

RELOC_RE = re.compile(r"^from:(0x[0-9a-f]+) kind:(\w+) to:(0x[0-9a-f]+)(?: add:(-?0x[0-9a-f]+))? module:(\S+)")
SEC_RE = re.compile(r"^\s+(\S+)\s+start:(0x[0-9a-f]+) end:(0x[0-9a-f]+) kind:(\w+)")
IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]*")
RENAME = {"main": "ffc_main"}
CONDS = ["z", "!z", "c", "!c", "n", "!n", "v", "!v", "(c && !z)", "(!c || z)", "(n == v)", "(n != v)",
         "(!z && n == v)", "(z || n != v)"]
NARGS = 10
ARGS = ", ".join(["u32"] * NARGS)

HEADER = r"""/* generated by tools/port_lift.py: Thumb functions lifted to C (not decompiled source) */
#include <stdint.h>
typedef uint32_t u32;
typedef int32_t s32;
typedef uint64_t u64;
#define LRMAGIC 0xfffffff1u
extern u32 ffc_r1;
extern void ffc_trap(const char *);
extern void ffc_lift_swi(u32 n, u32 *r);
extern u32 ffc_cpsr;
extern void ffc_cpsr_written(void);
static inline u32 clz32(u32 x) { return x ? (u32)__builtin_clz(x) : 32; }
typedef u32 (*ffc_fn)(u32, u32, u32, u32, u32, u32, u32, u32, u32, u32);
#define P(a) ((uintptr_t)(u32)(a))
#define L8(a) (*(volatile uint8_t *)P(a))
#define L16(a) (*(volatile uint16_t *)P(a))
#define L32(a) (*(volatile u32 *)P(a))
#define LS8(a) ((u32)(s32)(*(volatile int8_t *)P(a)))
#define LS16(a) ((u32)(s32)(*(volatile int16_t *)P(a)))
#define A(x) ((u32)(uintptr_t)(x))
#define NZ(x) (n = (s32)(x) < 0, z = (x) == 0)
#define STK(sp, i) L32((sp) + 4 * (i))
#define CALL(f) (r0 = (f)(r0, r1, r2, r3, STK(sp, 0), STK(sp, 1), STK(sp, 2), STK(sp, 3), STK(sp, 4), STK(sp, 5)), \
                 r1 = ffc_r1)
#define CALLV(f) ((void)(f)(r0, r1, r2, r3, STK(sp, 0), STK(sp, 1), STK(sp, 2), STK(sp, 3), STK(sp, 4), STK(sp, 5)))
#define RET() do { ffc_r1 = r1; return r0; } while (0)
static inline u32 lsl_c(u32 a, u32 s, u32 *c) { s &= 0xff; if (!s) return a; if (s < 32) { *c = (a >> (32 - s)) & 1; return a << s; } *c = s == 32 ? a & 1 : 0; return 0; }
static inline u32 lsr_c(u32 a, u32 s, u32 *c) { s &= 0xff; if (!s) return a; if (s < 32) { *c = (a >> (s - 1)) & 1; return a >> s; } *c = s == 32 ? a >> 31 : 0; return 0; }
static inline u32 asr_c(u32 a, u32 s, u32 *c) { s &= 0xff; if (!s) return a; if (s < 32) { *c = ((s32)a >> (s - 1)) & 1; return (u32)((s32)a >> s); } *c = a >> 31; return (u32)((s32)a >> 31); }
static inline u32 ror_c(u32 a, u32 s, u32 *c) { s &= 0xff; if (!s) return a; s &= 31; if (s) a = (a >> s) | (a << (32 - s)); *c = a >> 31; return a; }
"""


DTCM = 0x02fe0000


def sections(d: Path):
    out = []
    for line in (d / "delinks.txt").read_text().splitlines():
        if not line.startswith("    ."):
            if line.strip():
                break
            continue
        m = SEC_RE.match(line)
        if m:
            out.append((m[1], int(m[2], 16), int(m[3], 16), m[4]))
    return out


def nm_defined(objs):
    defined = set()
    for i in range(0, len(objs), 500):
        r = subprocess.run([os.environ.get("NM", "nm"), "--defined-only", "--format=posix"] + objs[i:i + 500],
                           capture_output=True, text=True)
        for line in r.stdout.splitlines():
            p = line.split()
            if len(p) >= 2 and p[1] not in ("a", "N", "n") and not p[0].endswith(":"):
                defined.add(p[0])
    return defined


class World:
    """Symbols, sections and relocations of every module, for naming lift targets."""

    def __init__(self):
        self.mods = list(ffclib.module_dirs())
        import port_gendata
        self.secs = {m: port_gendata.port_sections(m, d) for m, d in self.mods}
        self.syms = defaultdict(list)  # mod -> sorted [(addr, name, kind)]
        self.byname = {}
        for m, d in self.mods:
            for line in (d / "symbols.txt").read_text().splitlines():
                r = ffclib.SYM_RE.match(line)
                if r:
                    s = ffclib.Sym(r[1], r[2], r[3], int(r[4], 16), m)
                    self.syms[m].append((s.addr & ~1, s.name, s.kind))
                    self.byname.setdefault(s.name, s)
            self.syms[m].sort()
        self.abs = {}
        for line in (ffclib.CONFIG / "abs_symbols.txt").read_text().splitlines():
            r = ffclib.SYM_RE.match(line)
            if r:
                self.abs[int(r[4], 16) & ~1] = r[1]
        self.rel = {}
        for m, d in self.mods:
            rr = {}
            for line in (d / "relocs.txt").read_text().splitlines():
                r = RELOC_RE.match(line)
                if r:
                    rr[int(r[1], 16)] = (r[2], int(r[3], 16) + (int(r[4], 16) if r[4] else 0), r[5])
            self.rel[m] = rr

    def cands(self, mod, tm):
        if tm.startswith("overlays("):
            return ["ov%03d" % int(x) for x in tm[9:-1].split(",") if x.strip()]
        if tm.startswith("overlay("):
            return ["ov%03d" % int(tm[8:-1])]
        if tm in ("main", "itcm", "dtcm"):
            return [tm]
        return [mod, "main", "itcm", "dtcm"]

    def sec_of(self, m, addr):
        for name, lo, hi, kind in self.secs.get(m, ()):
            if lo <= addr < hi or (kind == "bss" and addr == hi):
                return name, lo, hi, kind
        return None

    def func_at(self, mods, addr):
        for m in mods:
            lst = self.syms.get(m, [])
            i = bisect.bisect_left(lst, (addr & ~1,))
            while i < len(lst) and lst[i][0] == addr & ~1:
                if lst[i][2] == "function":
                    return lst[i][1]
                i += 1
        if (addr & ~1) in self.abs:
            return self.abs[addr & ~1]
        return None

    def addr_expr(self, mod, to, tm, need):
        """C expression (u32) for the host address of DS address `to`; records the declarations it needs."""
        cands = self.cands(mod, tm)
        f = self.func_at(cands, to)
        if f:
            need[f] = "function"
            return f"A({cname(f)})"
        for m in cands:
            s = self.sec_of(m, to)
            if not s:
                continue
            name, lo, hi, kind = s
            lst = self.syms[m]
            i = bisect.bisect_right(lst, (to, "￿", "")) - 1
            while i >= 0 and lst[i][0] >= lo:
                a, n, k = lst[i]
                if k != "function" and IDENT.fullmatch(n):
                    need[n] = "data"
                    return f"(A({cname(n)}) + {to - a}u)" if to != a else f"A({cname(n)})"
                i -= 1
            b = f"ffc_blob_{m}{name}".replace(".", "_")
            need[b] = "data"
            return f"(A({b}) + {to - lo}u)"
        return f"{to:#x}u"


# Functions src/ defines with a `void` return: on the ARM they leave r0 (their first argument) untouched, on the host
# eax is garbage, so a lifted caller keeps its own r0 across the call (CALLV) instead of assigning the result.
# (A src function returning u64/struct or a non-void value needs nothing: r1 is only produced by lifted functions.)
VOID_DEFS = set()


def cname(n):
    return RENAME.get(n, n)


def sx(v, bits):
    return v - (1 << bits) if v & (1 << (bits - 1)) else v


class Lifter:
    def __init__(self, w: World, sym, data: bytes):
        self.w, self.s, self.b = w, sym, data
        self.mod = sym.module
        self.base = sym.addr & ~1
        self.need = {}
        self.out = []
        self.labels = set()
        self.computed = False
        self.ok = True

    def pool_word(self, addr):
        rng = ffclib.module_ranges()[self.mod]
        off = addr - rng[0]
        whole = ffclib._bin(self.mod)
        r = self.w.rel[self.mod].get(addr)
        if r and r[0] == "load":
            return self.w.addr_expr(self.mod, r[1], r[2], self.need)
        v = int.from_bytes(whole[off:off + 4], 'little')
        if DTCM <= v < DTCM + 0x4000:  # linker constants (arena/stack bounds): DTCM lives in a host blob
            self.need["ffc_blob_dtcm_data"] = "data"
            return f"(A(ffc_blob_dtcm_data) + {v - DTCM}u)"
        return f"{v:#x}u"

    def reg(self, i):
        return ["r0", "r1", "r2", "r3", "r4", "r5", "r6", "r7", "r8", "r9", "r10", "r11", "r12", "sp", "lr", "A(fcode)"][i]

    def pcv(self, off):
        return f"(A(fcode) + {off}u)"

    def target_name(self, addr):
        name = self.w.func_at([self.mod, "main", "itcm", "dtcm"], addr)
        if name:
            self.need[name] = "function"
        return name

    def call_named(self, name):
        if name in ("_s32_div_f", "_u32_div_f"):
            pass
        return f"{'CALLV' if name in VOID_DEFS else 'CALL'}({cname(name)});"

    def tail(self, name):
        return f"{{ {'CALLV' if name in VOID_DEFS else 'CALL'}({cname(name)}); RET(); }}"

    def lift(self):
        b, n = self.b, len(self.b)
        arm = self.s.mode == "arm"
        pools = ffclib.pool_offsets(b, self.base, self.s.mode)
        insns = []
        off = 0
        while off + (4 if arm else 2) <= n:
            if off in pools:
                off += 4
                continue
            if arm:
                insns.append((off, int.from_bytes(b[off:off + 4], "little"), 4))
                off += 4
                continue
            hw = int.from_bytes(b[off:off + 2], "little")
            size = 2
            if hw >> 11 in (0x1e,) and off + 4 <= n:
                lo = int.from_bytes(b[off + 2:off + 4], "little")
                if lo >> 11 in (0x1f, 0x1d):
                    size = 4
            insns.append((off, hw, size))
            off += size
        self.offs = [o for o, _, _ in insns]
        body = []
        self.prev_lr_pc = False
        for off, hw, size in insns:
            body.append((off, self.one_arm(off, hw) if arm else self.one(off, hw, size)))
        lines = []
        name = cname(self.s.name)
        lines.append(f"u32 {name}(u32 a0, u32 a1, u32 a2, u32 a3, u32 s0, u32 s1, u32 s2, u32 s3, u32 s4, u32 s5)")
        lines.append("{")
        lines.append(f"    static const uint8_t fcode[{max(n, 1)}] = {{{', '.join(str(x) for x in b) or '0'}}};")
        lines.append("    u32 stk[512];")
        lines.append("    u32 r0 = a0, r1 = a1, r2 = a2, r3 = a3, r4 = 0, r5 = 0, r6 = 0, r7 = 0, r8 = 0, r9 = 0, "
                     "r10 = 0, r11 = 0, r12 = 0, lr = LRMAGIC, sp = A(&stk[506]), n = 0, z = 0, c = 0, v = 0, t;")
        lines.append("    u64 w; u32 o2, sc;")
        lines.append("    stk[506] = s0; stk[507] = s1; stk[508] = s2; stk[509] = s3; stk[510] = s4; stk[511] = s5;")
        lines.append("    (void)fcode; (void)t; (void)w; (void)n; (void)z; (void)c; (void)v; (void)o2; (void)sc;")
        for off, code in body:
            if off in self.labels or self.computed:
                lines.append(f"L_{off:x}:;")
            lines.append(f"    {code}")
        lines.append("    RET();")
        if self.computed:
            lines.append("dispatch:")
            lines.append("    switch (t - A(fcode)) {")
            for o in self.offs:
                lines.append(f"    case {o}: goto L_{o:x};")
            lines.append(f"    default: ffc_trap(\"{self.s.name}: computed jump\"); RET();")
            lines.append("    }")
        lines.append("}")
        return lines

    def branch(self, off, target_off, cond=None):
        """goto inside the function, else a tail call."""
        pre = f"if ({cond}) " if cond else ""
        if 0 <= target_off < len(self.b) and target_off in self.offs:
            self.labels.add(target_off)
            return f"{pre}goto L_{target_off:x};"
        name = self.target_name(self.base + target_off)
        if name:
            return f"{pre}{self.tail(name)}"
        return f"{pre}{{ ffc_trap(\"{self.s.name}: branch to {self.base + target_off:#x}\"); RET(); }}"

    def write_reg(self, d, expr):
        """assignment to register d; a pc write becomes a jump."""
        if d == 15:
            self.computed = True
            return f"t = {expr}; if (t == LRMAGIC) RET(); goto dispatch;"
        return f"{self.reg(d)} = {expr};"

    def one(self, off, hw, size):
        R = self.reg
        pc4 = off + 4
        op = hw >> 13
        if size == 4:
            lo = int.from_bytes(self.b[off + 2:off + 4], "little")
            disp = (sx(hw & 0x7ff, 11) << 12) + ((lo & 0x7ff) << 1)
            tgt = self.base + pc4 + disp
            if lo >> 11 == 0x1d:
                tgt &= ~3
            r = self.w.rel[self.mod].get(self.base + off)
            name = None
            if r and r[0] in ("thumb_call", "thumb_call_arm"):
                name = self.w.func_at(self.w.cands(self.mod, r[2]), r[1])
            if name is None:
                name = self.w.func_at([self.mod, "main", "itcm", "dtcm"], tgt)
            if name is None:
                return f"ffc_trap(\"{self.s.name}: call to {tgt:#x}\");"
            self.need[name] = "function"
            return self.call_named(name)
        if hw >> 11 == 0x1e:  # lone BL prefix
            return f"lr = {self.pcv(pc4)};"
        if op == 0:
            if (hw >> 11) & 3 != 3:  # shift imm
                kind, imm, s, d = (hw >> 11) & 3, (hw >> 6) & 31, R((hw >> 3) & 7), R(hw & 7)
                if kind == 0:
                    if imm == 0:
                        return f"{d} = {s}; NZ({d});"
                    return f"c = ({s} >> {32 - imm}) & 1; {d} = {s} << {imm}; NZ({d});"
                if kind == 1:
                    if imm == 0:
                        return f"c = {s} >> 31; {d} = 0; NZ({d});"
                    return f"c = ({s} >> {imm - 1}) & 1; {d} = {s} >> {imm}; NZ({d});"
                if imm == 0:
                    return f"c = {s} >> 31; {d} = (u32)((s32){s} >> 31); NZ({d});"
                return f"c = ((s32){s} >> {imm - 1}) & 1; {d} = (u32)((s32){s} >> {imm}); NZ({d});"
            imm_f, sub, rn = (hw >> 10) & 1, (hw >> 9) & 1, (hw >> 6) & 7
            s, d = R((hw >> 3) & 7), R(hw & 7)
            b_ = f"{rn}u" if imm_f else R(rn)
            return self.addsub(d, s, b_, sub)
        if op == 1:
            kind, d, imm = (hw >> 11) & 3, R((hw >> 8) & 7), hw & 0xff
            if kind == 0:
                return f"{d} = {imm}u; NZ({d});"
            if kind == 1:
                return self.addsub(None, d, f"{imm}u", 1)
            return self.addsub(d, d, f"{imm}u", kind == 3)
        if hw >> 10 == 0x10:  # ALU
            o, s, d = (hw >> 6) & 15, R((hw >> 3) & 7), R(hw & 7)
            simple = {0: "&", 1: "^", 12: "|"}
            if o in simple:
                return f"{d} = {d} {simple[o]} {s}; NZ({d});"
            if o == 14:
                return f"{d} = {d} & ~{s}; NZ({d});"
            if o == 15:
                return f"{d} = ~{s}; NZ({d});"
            if o == 8:
                return f"t = {d} & {s}; NZ(t);"
            if o == 13:
                return f"{d} = {d} * {s}; NZ({d});"
            if o in (2, 3, 4, 7):
                fn = {2: "lsl_c", 3: "lsr_c", 4: "asr_c", 7: "ror_c"}[o]
                return f"{d} = {fn}({d}, {s}, &c); NZ({d});"
            if o == 5:
                return (f"w = (u64){d} + {s} + c; t = (u32)w; v = (~({d} ^ {s}) & ({d} ^ t)) >> 31; c = (u32)(w >> 32); "
                        f"{d} = t; NZ({d});")
            if o == 6:
                return (f"w = (u64){d} - {s} - !c; t = (u32)w; v = (({d} ^ {s}) & ({d} ^ t)) >> 31; c = !(u32)(w >> 32); "
                        f"{d} = t; NZ({d});")
            if o == 9:
                return self.addsub(d, "0u", s, 1)
            if o == 10:
                return self.addsub(None, d, s, 1)
            if o == 11:
                return self.addsub(None, d, s, 0)
        if hw >> 10 == 0x11:  # hi register ops / bx
            o, h1, h2 = (hw >> 8) & 3, (hw >> 7) & 1, (hw >> 6) & 1
            sn, dn = ((hw >> 3) & 7) | (h2 << 3), (hw & 7) | (h1 << 3)
            src = self.pcv(pc4) if sn == 15 else R(sn)
            if o == 0:
                dst = self.pcv(pc4) if dn == 15 else R(dn)
                return self.write_reg(dn, f"{dst} + {src}")
            if o == 1:
                return self.addsub(None, R(dn), src, 1)
            if o == 2:
                if dn == 8 and sn == 8:
                    return ";"  # nop
                return self.write_reg(dn, src)
            # bx / blx
            if h1:
                return f"CALL(((ffc_fn)P({src})));"
            if sn == 14:
                return "RET();"
            return f"if ({src} == LRMAGIC) RET(); {{ CALL(((ffc_fn)P({src}))); RET(); }}"
        if hw >> 11 == 9:  # ldr pc-rel
            d, imm = R((hw >> 8) & 7), (hw & 0xff) * 4
            return f"{d} = {self.pool_word(self.base + (pc4 & ~3) + imm)};"
        if hw >> 12 == 5:  # load/store register offset
            o, ro, rb, rd = (hw >> 9) & 7, R((hw >> 6) & 7), R((hw >> 3) & 7), R(hw & 7)
            a = f"{rb} + {ro}"
            return [f"L32({a}) = {rd};", f"L16({a}) = (uint16_t){rd};", f"L8({a}) = (uint8_t){rd};",
                    f"{rd} = LS8({a});", f"{rd} = L32({a});", f"{rd} = L16({a});", f"{rd} = L8({a});",
                    f"{rd} = LS16({a});"][o]
        if op == 3:  # load/store imm
            bb, ld, imm, rb, rd = (hw >> 12) & 1, (hw >> 11) & 1, (hw >> 6) & 31, R((hw >> 3) & 7), R(hw & 7)
            if bb:
                a = f"{rb} + {imm}u"
                return f"{rd} = L8({a});" if ld else f"L8({a}) = (uint8_t){rd};"
            a = f"{rb} + {imm * 4}u"
            return f"{rd} = L32({a});" if ld else f"L32({a}) = {rd};"
        if hw >> 12 == 8:
            ld, imm, rb, rd = (hw >> 11) & 1, (hw >> 6) & 31, R((hw >> 3) & 7), R(hw & 7)
            a = f"{rb} + {imm * 2}u"
            return f"{rd} = L16({a});" if ld else f"L16({a}) = (uint16_t){rd};"
        if hw >> 12 == 9:
            ld, rd, imm = (hw >> 11) & 1, R((hw >> 8) & 7), (hw & 0xff) * 4
            return f"{rd} = L32(sp + {imm}u);" if ld else f"L32(sp + {imm}u) = {rd};"
        if hw >> 12 == 0xa:
            spf, rd, imm = (hw >> 11) & 1, R((hw >> 8) & 7), (hw & 0xff) * 4
            return f"{rd} = sp + {imm}u;" if spf else f"{rd} = {self.pcv((pc4 & ~3) + imm)};"
        if hw >> 8 == 0xb0:
            imm = (hw & 0x7f) * 4
            return f"sp -= {imm}u;" if hw & 0x80 else f"sp += {imm}u;"
        if hw >> 12 == 0xb and (hw >> 9) & 3 == 2:  # push/pop
            ld, rr, rl = (hw >> 11) & 1, (hw >> 8) & 1, hw & 0xff
            regs = [i for i in range(8) if rl >> i & 1]
            if ld:
                code = [f"{R(r)} = L32(sp + {4 * i}u);" for i, r in enumerate(regs)]
                if rr:
                    code.append(f"t = L32(sp + {4 * len(regs)}u);")
                code.append(f"sp += {4 * (len(regs) + rr)}u;")
                if rr:
                    code.append("RET();")
                return " ".join(code)
            regs = regs + ([14] if rr else [])
            code = [f"sp -= {4 * len(regs)}u;"] + [f"L32(sp + {4 * i}u) = {R(r)};" for i, r in enumerate(regs)]
            return " ".join(code)
        if hw >> 8 == 0xbe:
            return f"ffc_trap(\"{self.s.name}: bkpt\");"
        if hw >> 12 == 0xc:  # ldmia/stmia
            ld, rb, rl = (hw >> 11) & 1, (hw >> 8) & 7, hw & 0xff
            regs = [i for i in range(8) if rl >> i & 1]
            code = [f"t = {R(rb)};"]
            for i, r in enumerate(regs):
                code.append(f"{R(r)} = L32(t + {4 * i}u);" if ld else f"L32(t + {4 * i}u) = {R(r)};")
            if not (ld and rb in regs):
                code.append(f"{R(rb)} = t + {4 * len(regs)}u;")
            return " ".join(code)
        if hw >> 12 == 0xd:
            cond = (hw >> 8) & 15
            if cond == 15:
                return f"{{ u32 rr[4] = {{r0, r1, r2, r3}}; ffc_lift_swi({hw & 0xff}u, rr); " \
                       f"r0 = rr[0]; r1 = rr[1]; r2 = rr[2]; r3 = rr[3]; }}"
            if cond == 14:
                self.ok = False
                return f"ffc_trap(\"{self.s.name}: undefined\");"
            return self.branch(off, pc4 + sx(hw & 0xff, 8) * 2, CONDS[cond])
        if hw >> 11 == 0x1c:
            return self.branch(off, pc4 + sx(hw & 0x7ff, 11) * 2)
        self.ok = False
        return f"ffc_trap(\"{self.s.name}: undecoded {hw:#06x}\");"


    # ---- ARM mode -------------------------------------------------------------------------------------------
    def op2_shift(self, off, w, want_c):
        """(code, expr) for the data-processing / LDR register operand of w; sets sc when want_c."""
        R = self.reg
        rm = w & 15
        m = self.pcv(off + 8) if rm == 15 else R(rm)
        kind = (w >> 5) & 3
        fn = ["lsl_c", "lsr_c", "asr_c", "ror_c"][kind]
        if w & 0x10:  # shift by register
            rs = R((w >> 8) & 15)
            return f"sc = c; o2 = {fn}({m}, {rs}, &sc);", "o2"
        imm = (w >> 7) & 31
        if kind == 0 and imm == 0:
            return ("sc = c;" if want_c else ""), m
        if kind == 3 and imm == 0:  # rrx
            return f"sc = {m} & 1; o2 = ({m} >> 1) | (c << 31);", "o2"
        if kind in (1, 2) and imm == 0:
            imm = 32
        return f"sc = c; o2 = {fn}({m}, {imm}, &sc);", "o2"

    def one_arm(self, off, w):
        prev, self.prev_lr_pc = self.prev_lr_pc, False
        cond = w >> 28
        code = self.arm_body(off, w, prev)
        if cond == 14 or cond == 15:
            return code
        return f"if ({CONDS[cond]}) {{ {code} }}"

    def arm_pc_write(self, expr, prev):
        """pc <- expr; after `mov lr, pc` it is a call that returns to the next instruction."""
        if prev:
            return f"t = {expr}; CALL(((ffc_fn)P(t)));"
        self.computed = True
        return f"t = {expr}; if (t == LRMAGIC) RET(); goto dispatch;"

    def arm_body(self, off, w, prev):
        R = self.reg
        nm = self.s.name
        pc8 = off + 8
        if w >> 28 == 15:
            if (w >> 25) & 7 == 5:  # blx imm
                tgt = self.base + pc8 + (sx(w & 0xffffff, 24) << 2) + ((w >> 23) & 2)
                return self.arm_call(off, tgt)
            if (w & 0x0d70f000) == 0x0550f000:
                return ";"  # pld
            self.ok = False
            return f'ffc_trap("{nm}: undecoded arm {w:#010x}");'
        if (w & 0x0ffffff0) == 0x012fff10:  # bx
            rm = w & 15
            if rm == 14:
                return "RET();"
            if prev:
                return f"CALL(((ffc_fn)P({R(rm)})));"
            return f"if ({R(rm)} == LRMAGIC) RET(); {{ CALL(((ffc_fn)P({R(rm)}))); RET(); }}"
        if (w & 0x0ffffff0) == 0x012fff30:  # blx reg
            return f"CALL(((ffc_fn)P({R(w & 15)})));"
        if (w & 0x0fff0ff0) == 0x016f0f10:
            return f"{R((w >> 12) & 15)} = clz32({R(w & 15)});"
        if (w & 0x0fbf0fff) == 0x010f0000:  # mrs
            return f"{R((w >> 12) & 15)} = ffc_cpsr;" if not w & (1 << 22) else f"{R((w >> 12) & 15)} = 0;"
        if (w & 0x0fb0fff0) == 0x0120f000 or (w & 0x0fb0f000) == 0x0320f000:  # msr
            if w & (1 << 22):
                return ";"
            if w & (1 << 25):
                rot = ((w >> 8) & 15) * 2
                v = w & 0xff
                v = ((v >> rot) | (v << (32 - rot))) & 0xffffffff if rot else v
                src = f"{v:#x}u"
            else:
                src = R(w & 15)
            mask = 0
            for i in range(4):
                if w >> (16 + i) & 1:
                    mask |= 0xff << (8 * i)
            code = f"ffc_cpsr = (ffc_cpsr & ~{mask:#x}u) | ({src} & {mask:#x}u);"
            if mask & 0xff000000:
                code += " n = ffc_cpsr >> 31; z = (ffc_cpsr >> 30) & 1; c = (ffc_cpsr >> 29) & 1; v = (ffc_cpsr >> 28) & 1;"
            if mask & 0xff and not w & (1 << 22):
                code += " ffc_cpsr_written();"
            return code
        if (w >> 24) & 15 == 15:  # swi
            return (f"{{ u32 rr[4] = {{r0, r1, r2, r3}}; ffc_lift_swi({(w >> 16) & 0xff}u, rr); "
                    f"r0 = rr[0]; r1 = rr[1]; r2 = rr[2]; r3 = rr[3]; }}")
        if (w >> 24) & 15 == 14:  # cdp / mcr / mrc
            if w & 0x10 and w & (1 << 20):
                rd = (w >> 12) & 15
                return ";" if rd == 15 else f"{R(rd)} = 0;"
            return ";"
        if (w >> 25) & 7 == 6:
            return ";"  # ldc/stc
        if (w >> 25) & 7 == 5:  # b / bl
            tgt_off = pc8 + (sx(w & 0xffffff, 24) << 2)
            if w & (1 << 24):
                return self.arm_call(off, self.base + tgt_off)
            return self.branch(off, tgt_off)
        if (w >> 25) & 7 == 4:
            return self.arm_ldm(w, prev)
        if (w & 0x0fc000f0) == 0x00000090:  # mul / mla
            d, rn, rs, rm = R((w >> 16) & 15), R((w >> 12) & 15), R((w >> 8) & 15), R(w & 15)
            e = f"{rm} * {rs}" + (f" + {rn}" if w & (1 << 21) else "")
            return f"{d} = {e};" + (f" NZ({d});" if w & (1 << 20) else "")
        if (w & 0x0f8000f0) == 0x00800090:  # long multiply
            hi, lo, rs, rm = R((w >> 16) & 15), R((w >> 12) & 15), R((w >> 8) & 15), R(w & 15)
            signed, acc = w & (1 << 22), w & (1 << 21)
            e = f"(u64)((int64_t)(s32){rm} * (s32){rs})" if signed else f"(u64){rm} * {rs}"
            if acc:
                e += f" + (((u64){hi} << 32) | {lo})"
            code = f"w = {e}; {lo} = (u32)w; {hi} = (u32)(w >> 32);"
            if w & (1 << 20):
                code += f" n = {hi} >> 31; z = w == 0;"
            return code
        if (w & 0x0f900090) == 0x01000080:  # DSP multiplies
            op = (w >> 21) & 3
            d, rn, rs, rm = R((w >> 16) & 15), R((w >> 12) & 15), R((w >> 8) & 15), R(w & 15)
            x, y = (w >> 5) & 1, (w >> 6) & 1
            hx = f"(s32)(int16_t)({rm} >> 16)" if x else f"(s32)(int16_t){rm}"
            hy = f"(s32)(int16_t)({rs} >> 16)" if y else f"(s32)(int16_t){rs}"
            if op == 0:
                return f"{d} = (u32)({hx} * {hy}) + {rn};"
            if op == 1:
                p_ = f"(u32)(((int64_t)(s32){rm} * {hy}) >> 16)"
                return f"{d} = {p_};" if x else f"{d} = {p_} + {rn};"
            if op == 2:
                return f"w = (((u64){d} << 32) | {rn}) + (u64)(int64_t)({hx} * {hy}); {rn} = (u32)w; {d} = (u32)(w >> 32);"
            return f"{d} = (u32)({hx} * {hy});"
        if (w & 0x0e000090) == 0x00000090 and (w >> 5) & 3:  # ldrh/strh/ldrsb/ldrsh/ldrd/strd
            return self.arm_half(off, w)
        if (w & 0x0fb00ff0) == 0x01000090:  # swp
            d, rn, rm = R((w >> 12) & 15), R((w >> 16) & 15), R(w & 15)
            if w & (1 << 22):
                return f"t = L8({rn}); L8({rn}) = (uint8_t){rm}; {d} = t;"
            return f"t = L32({rn}); L32({rn}) = {rm}; {d} = t;"
        if (w >> 26) & 3 == 1:
            return self.arm_ldr(off, w, prev)
        if (w >> 26) & 3 == 0:
            return self.arm_dp(off, w, prev)
        self.ok = False
        return f'ffc_trap("{nm}: undecoded arm {w:#010x}");'

    def arm_call(self, off, tgt):
        r = self.w.rel[self.mod].get(self.base + off)
        name = None
        if r and r[0] in ("arm_call", "arm_call_thumb", "arm_branch"):
            name = self.w.func_at(self.w.cands(self.mod, r[2]), r[1])
        if name is None:
            name = self.w.func_at([self.mod, "main", "itcm", "dtcm"], tgt)
        if name is None:
            return f'ffc_trap("{self.s.name}: call to {tgt:#x}");'
        self.need[name] = "function"
        return self.call_named(name)

    def arm_dp(self, off, w, prev):
        R = self.reg
        op, sflag = (w >> 21) & 15, (w >> 20) & 1
        rn_i, rd_i = (w >> 16) & 15, (w >> 12) & 15
        rn = self.pcv(off + 8) if rn_i == 15 else R(rn_i)
        logical = op in (0, 1, 8, 9, 12, 13, 14, 15)
        pre = ""
        if w & (1 << 25):
            rot = ((w >> 8) & 15) * 2
            v = w & 0xff
            v = ((v >> rot) | (v << (32 - rot))) & 0xffffffff if rot else v
            b = f"{v:#x}u"
            if sflag and logical and rot:
                pre = f"sc = {v >> 31}u;"
            elif sflag and logical:
                pre = "sc = c;"
        else:
            pre, b = self.op2_shift(off, w, sflag and logical)
        if op in (8, 9, 10, 11):  # tst teq cmp cmn
            if op == 8:
                return f"{pre} t = {rn} & {b}; NZ(t); c = sc;"
            if op == 9:
                return f"{pre} t = {rn} ^ {b}; NZ(t); c = sc;"
            return pre + " " + self.addsub(None, rn, b, op == 10)
        if logical:
            e = {0: f"{rn} & {b}", 1: f"{rn} ^ {b}", 12: f"{rn} | {b}", 13: b, 14: f"{rn} & ~{b}", 15: f"~{b}"}[op]
            if rd_i == 15:
                if rn_i == 14 or b == "lr":
                    pass
                return pre + " " + self.arm_pc_write(e, prev)
            if op == 13 and rd_i == 14 and b == self.pcv(off + 8):
                self.prev_lr_pc = True
            code = f"{pre} {R(rd_i)} = {e};"
            if sflag:
                code += f" NZ({R(rd_i)}); c = sc;"
            return code
        # arithmetic: sub rsb add adc sbc rsc
        a_, b_ = (b, rn) if op in (3, 7) else (rn, b)
        if op in (2, 3, 4):
            if not sflag or rd_i == 15:  # `subs pc, lr, #4` = exception return
                e = f"{a_} - {b_}" if op != 4 else f"{a_} + {b_}"
                return pre + " " + (self.arm_pc_write(e, prev) if rd_i == 15 else f"{R(rd_i)} = {e};")
            return pre + " " + self.addsub(R(rd_i), a_, b_, op != 4)
        if op == 5:  # adc
            code = (f"w = (u64){a_} + {b_} + c; t = (u32)w;" +
                    (f" v = (~({a_} ^ {b_}) & ({a_} ^ t)) >> 31; c = (u32)(w >> 32); NZ(t);" if sflag else ""))
        else:  # sbc / rsc
            code = (f"w = (u64){a_} - {b_} - !c; t = (u32)w;" +
                    (f" v = (({a_} ^ {b_}) & ({a_} ^ t)) >> 31; c = !(u32)(w >> 32); NZ(t);" if sflag else ""))
        return f"{pre} {code} {R(rd_i)} = t;"

    def arm_addr(self, off, w, offs_expr):
        """(pre, address, writeback) for a load/store with base rn."""
        R = self.reg
        rn_i = (w >> 16) & 15
        P, U, W = (w >> 24) & 1, (w >> 23) & 1, (w >> 21) & 1
        sign = "+" if U else "-"
        rn = self.pcv(off + 8) if rn_i == 15 else R(rn_i)
        if P:
            a = f"({rn} {sign} {offs_expr})"
            wb = f"{R(rn_i)} = {a};" if W else ""
            return a, wb
        return rn, f"{R(rn_i)} = {rn} {sign} {offs_expr};"

    def arm_ldr(self, off, w, prev):
        R = self.reg
        rd_i, rn_i = (w >> 12) & 15, (w >> 16) & 15
        L, B = (w >> 20) & 1, (w >> 22) & 1
        pre = ""
        if w & (1 << 25):
            pre, o = self.op2_shift(off, w & ~0x10, False)
        else:
            o = f"{w & 0xfff}u"
        if rn_i == 15 and not w & (1 << 25) and L and not B and (w >> 24) & 1:
            addr = self.base + off + 8 + ((w & 0xfff) if (w >> 23) & 1 else -(w & 0xfff))
            val = self.pool_word(addr) if 0 <= addr - self.base < len(self.b) else f"L32({addr:#x}u)"
            return self.arm_pc_write(val, prev) if rd_i == 15 else f"{R(rd_i)} = {val};"
        a, wb = self.arm_addr(off, w, o)
        if L:
            ld = f"L8({a})" if B else f"L32({a})"
            if rd_i == 15:
                return f"{pre} o2 = {ld}; {wb} " + self.arm_pc_write("o2", prev)
            return f"{pre} t = {ld}; {wb} {R(rd_i)} = t;"
        st = f"L8({a}) = (uint8_t){R(rd_i)};" if B else f"L32({a}) = {self.pcv(off + 12) if rd_i == 15 else R(rd_i)};"
        return f"{pre} {st} {wb}"

    def arm_half(self, off, w):
        R = self.reg
        rd_i = (w >> 12) & 15
        L, sh = (w >> 20) & 1, (w >> 5) & 3
        o = f"{((w >> 4) & 0xf0) | (w & 15)}u" if w & (1 << 22) else R(w & 15)
        a, wb = self.arm_addr(off, w, o)
        rd = R(rd_i)
        if L:
            ld = {1: f"L16({a})", 2: f"LS8({a})", 3: f"LS16({a})"}[sh]
            return f"t = {ld}; {wb} {rd} = t;"
        if sh == 1:
            return f"L16({a}) = (uint16_t){rd}; {wb}"
        if sh == 2:  # ldrd
            return f"t = {a}; {rd} = L32(t); {R(rd_i + 1)} = L32(t + 4u); {wb}"
        return f"t = {a}; L32(t) = {rd}; L32(t + 4u) = {R(rd_i + 1)}; {wb}"

    def arm_ldm(self, w, prev):
        R = self.reg
        rn_i, rl = (w >> 16) & 15, w & 0xffff
        P, U, W, L = (w >> 24) & 1, (w >> 23) & 1, (w >> 21) & 1, (w >> 20) & 1
        regs = [i for i in range(16) if rl >> i & 1]
        k = len(regs)
        start = {(0, 1): 0, (1, 1): 4, (0, 0): -4 * k + 4, (1, 0): -4 * k}[(P, U)]
        code = [f"t = {R(rn_i)};"]
        pc_load = None
        for i, r in enumerate(regs):
            a = f"t + {start + 4 * i}u" if start + 4 * i >= 0 else f"t - {-(start + 4 * i)}u"
            if L:
                if r == 15:
                    pc_load = f"L32({a})"
                else:
                    code.append(f"{R(r)} = L32({a});")
            else:
                code.append(f"L32({a}) = {R(r)};")
        if W and not (L and rn_i in regs):
            code.append(f"{R(rn_i)} = t {'+' if U else '-'} {4 * k}u;")
        if pc_load:
            code.insert(1, f"o2 = {pc_load};")
            code.append("RET();" if rn_i == 13 else self.arm_pc_write("o2", prev))
        return " ".join(code)

    @staticmethod
    def addsub(d, a, b, sub):
        if sub:
            core = f"t = {a} - {b}; c = {a} >= {b}; v = (({a} ^ {b}) & ({a} ^ t)) >> 31; NZ(t);"
        else:
            core = f"w = (u64){a} + {b}; t = (u32)w; c = (u32)(w >> 32); v = (~({a} ^ {b}) & ({a} ^ t)) >> 31; NZ(t);"
        return core + (f" {d} = t;" if d else "")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--objs", type=Path, required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--chunks", type=int, default=32)
    ap.add_argument("--only", nargs="*")
    a = ap.parse_args()
    objs = [l for l in a.objs.read_text().split() if l and "/lift/" not in l]
    defined = nm_defined(objs)
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import port_argpad
    VOID_DEFS.update(port_argpad.void_names())
    w = World()
    todo = []
    for name, s in w.byname.items():
        if s.kind != "function" or s.mode not in ("thumb", "arm") or not s.size or cname(name) in defined or name in defined:
            continue
        if not IDENT.fullmatch(name) or (a.only and name not in a.only):
            continue
        todo.append(s)
    todo.sort(key=lambda s: (s.module, s.addr))
    a.out.mkdir(parents=True, exist_ok=True)
    chunks = [[] for _ in range(a.chunks)]
    stats = defaultdict(int)
    for i, s in enumerate(todo):
        data = ffclib.target_bytes(s)
        L = Lifter(w, s, data)
        lines = L.lift()
        stats["ok" if L.ok else "partial"] += 1
        chunks[i % a.chunks].append((L.need, lines, s.name))
    for k, ch in enumerate(chunks):
        need, defs = {}, set()
        for nd, _, nm in ch:
            need.update(nd)
            defs.add(nm)
        out = [HEADER]
        for n, kind in sorted(need.items()):
            if n in defs:
                continue
            if kind == "function":
                out.append(f"u32 {cname(n)}({ARGS});")
            else:
                out.append(f"extern uint8_t {cname(n)}[];")
        for _, _, nm in ch:
            out.append(f"u32 {cname(nm)}({ARGS});")
        for _, lines, _ in ch:
            out.append("\n".join(lines))
        text = "\n".join(out) + "\n"
        p = a.out / f"lift_{k:03d}.c"
        if not p.exists() or p.read_text() != text:
            p.write_text(text)
    (a.out / "lifted.txt").write_text("".join(s.name + "\n" for s in todo))
    print(f"lifted {len(todo)} functions ({stats['ok']} clean, {stats['partial']} with traps) "
          f"-> {a.out}/lift_*.c", file=sys.stderr)


if __name__ == "__main__":
    main()
